package lattesite.localization.text;

/** Represents a localized text string in Slovak. */
public class Slovak extends LocalizedText {

    /**
     * @param text the Slovak text
     * @return a new {@link Slovak} instance
     */
    public static Slovak Slovak(String text) {
        return new Slovak(text);
    }

    public Slovak(String text) {
        super(text);
    }

}
