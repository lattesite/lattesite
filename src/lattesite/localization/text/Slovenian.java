package lattesite.localization.text;

/** Represents a localized text string in Slovenian. */
public class Slovenian extends LocalizedText {

    /**
     * @param text the Slovenian text
     * @return a new {@link Slovenian} instance
     */
    public static Slovenian Slovenian(String text) {
        return new Slovenian(text);
    }

    public Slovenian(String text) {
        super(text);
    }

}
