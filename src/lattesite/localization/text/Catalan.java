package lattesite.localization.text;

/** Represents a localized text string in Catalan. */
public class Catalan extends LocalizedText {

    /**
     * @param text the Catalan text
     * @return a new {@link Catalan} instance
     */
    public static Catalan Catalan(String text) {
        return new Catalan(text);
    }

    public Catalan(String text) {
        super(text);
    }

}
