package lattesite.localization.text;

/** Represents a localized text string in Filipino. */
public class Filipino extends LocalizedText {

    /**
     * @param text the Filipino text
     * @return a new {@link Filipino} instance
     */
    public static Filipino Filipino(String text) {
        return new Filipino(text);
    }

    public Filipino(String text) {
        super(text);
    }

}
