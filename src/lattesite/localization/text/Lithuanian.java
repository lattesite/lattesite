package lattesite.localization.text;

/** Represents a localized text string in Lithuanian. */
public class Lithuanian extends LocalizedText {

    /**
     * @param text the Lithuanian text
     * @return a new {@link Lithuanian} instance
     */
    public static Lithuanian Lithuanian(String text) {
        return new Lithuanian(text);
    }

    public Lithuanian(String text) {
        super(text);
    }

}
