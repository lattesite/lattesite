package lattesite.localization.text;

/** Represents a localized text string in Portuguese. */
public class Portuguese extends LocalizedText {

    /**
     * @param text the Portuguese text
     * @return a new {@link Portuguese} instance
     */
    public static Portuguese Portuguese(String text) {
        return new Portuguese(text);
    }

    public Portuguese(String text) {
        super(text);
    }

}
